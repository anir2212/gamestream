"""Versioned synthetic fixture export with an event-ID manifest.

A fixture directory holds `events.jsonl` (deliveries in publish order, including the
intentional duplicates) and `manifest.json`. The manifest names the fixture version,
generator inputs, counts, the SHA-256 of the sorted unique event IDs and the expected
answers to the five `bench/query_bench.py` queries. Both sinks can then be checked
against the same IDs and answers before any latency is timed. Exports contain no
wall-clock values, so the same inputs always produce byte-identical files.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from collections import Counter
from collections.abc import Iterable
from datetime import UTC, datetime
from pathlib import Path

from gamestream_producer.generator import GENERATOR_VERSION, generate_events

MANIFEST_FORMAT = 1
EVENTS_FILE = "events.jsonl"
MANIFEST_FILE = "manifest.json"
ID_HASH_RULE = "sha256 of UTF-8 sorted unique event IDs joined by a newline"
LATE_MS = 30 * 60 * 1000
_VERSION = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$")


def event_id_digest(event_ids: Iterable[str]) -> str:
    """Hash a set of event IDs in a sink-independent order."""
    return hashlib.sha256("\n".join(sorted(set(event_ids))).encode()).hexdigest()


def expected_answers(rows: list[dict]) -> dict[str, list[str]]:
    """Answers to the benchmark queries over the deduplicated fixture.

    Values are strings so they compare directly with normalized Trino and ClickHouse
    results. Duplicate deliveries repeat the whole record, so keeping the first
    delivery per ID matches silver `MERGE` and ClickHouse `FINAL`.
    """
    events = list({row["event_id"]: row for row in reversed(rows)}.values())
    purchases = [row for row in events if row["event_type"] == "purchase"]
    revenue = sum(row["amount_cents"] for row in purchases)
    games = Counter(row["game_id"] for row in events)
    top_game, top_count = min(games.items(), key=lambda item: (-item[1], item[0]))
    return {
        "row_count": [str(len(events))],
        "purchase_count": [str(len(purchases))],
        "active_users": [str(len({row["user_id"] for row in events}))],
        "revenue": [str(revenue) if purchases else "NULL"],
        "top_game": [top_game, str(top_count)],
    }


def _iso_ms(value: int) -> str:
    return datetime.fromtimestamp(value / 1000, tz=UTC).isoformat().replace("+00:00", "Z")


def _events_bytes(rows: list[dict]) -> bytes:
    return "".join(json.dumps(row, sort_keys=True) + "\n" for row in rows).encode()


def build_manifest(rows: list[dict], *, version: str, seed: int, count: int,
                   start: datetime) -> dict:
    """Describe exported deliveries; the hash rule matches `bench/query_bench.py`."""
    unique = {row["event_id"]: row for row in reversed(rows)}
    events = list(unique.values())
    ids = sorted(unique)
    event_times = [row["event_ts"] for row in events]
    return {
        "manifest_format": MANIFEST_FORMAT,
        "fixture_version": version,
        "data_origin": "synthetic; generated by this repository, no external source data",
        "generator": {
            "function": "gamestream_producer.generator.generate_events",
            "generator_version": GENERATOR_VERSION,
            "seed": seed,
            "count": count,
            "start_utc": start.astimezone(UTC).isoformat().replace("+00:00", "Z"),
            "duplicate_rate": 0.02,
            "late_rate": 0.01,
            "users": 200,
            "games": 40,
        },
        "deliveries": len(rows),
        "unique_event_ids": len(ids),
        "duplicate_deliveries": len(rows) - len(ids),
        "late_events": sum(row["ingest_ts"] - row["event_ts"] == LATE_MS for row in events),
        "schema_versions": {
            str(version_id): total
            for version_id, total in sorted(Counter(r["schema_version"] for r in events).items())
        },
        "event_id_prefix": f"e-{seed}-",
        "first_event_id": ids[0] if ids else None,
        "last_event_id": ids[-1] if ids else None,
        "event_ids_sha256": event_id_digest(ids),
        "event_id_hash_rule": ID_HASH_RULE,
        "event_ts_min_utc": _iso_ms(min(event_times)) if events else None,
        "event_ts_max_utc": _iso_ms(max(event_times)) if events else None,
        "event_dates_utc": sorted({_iso_ms(value)[:10] for value in event_times}),
        "events_file": EVENTS_FILE,
        "events_sha256": hashlib.sha256(_events_bytes(rows)).hexdigest(),
        "expected_answers": expected_answers(rows) if events else {},
    }


def build_fixture(version: str, *, count: int, seed: int,
                  start: datetime) -> tuple[list[dict], dict]:
    if not _VERSION.fullmatch(version):
        raise ValueError("fixture version must be 1-64 letters, digits, '.', '_' or '-'")
    if count < 1:
        raise ValueError("a fixture needs at least one event")
    if seed < 0:
        raise ValueError("seed must be nonnegative so the event-ID prefix stays parseable")
    if start.tzinfo is None:
        raise ValueError("start must have a timezone")
    rows = generate_events(count, seed=seed, start=start)
    return rows, build_manifest(rows, version=version, seed=seed, count=count, start=start)


def _manifest_bytes(manifest: dict) -> bytes:
    return (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()


def write_fixture(directory: Path, version: str, *, count: int, seed: int,
                  start: datetime) -> dict:
    """Write the fixture; an identical re-export succeeds, a different one is refused."""
    rows, manifest = build_fixture(version, count=count, seed=seed, start=start)
    outputs = {EVENTS_FILE: _events_bytes(rows), MANIFEST_FILE: _manifest_bytes(manifest)}
    for name, content in outputs.items():
        path = directory / name
        if path.exists() and path.read_bytes() != content:
            raise FileExistsError(f"{path} exists with different content; choose a new version")
    directory.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        (directory / name).write_bytes(content)
    return manifest


def load_manifest(path: Path) -> dict:
    manifest = json.loads(path.read_text())
    if manifest.get("manifest_format") != MANIFEST_FORMAT:
        raise ValueError(f"Unsupported manifest format in {path}")
    if not re.fullmatch(r"e-\d+-", manifest.get("event_id_prefix", "")):
        raise ValueError("Manifest event_id_prefix must look like 'e-<seed>-'")
    return manifest


def load_fixture(directory: Path) -> tuple[list[dict], dict]:
    """Read deliveries and refuse them if they no longer match the manifest."""
    manifest = load_manifest(directory / MANIFEST_FILE)
    content = (directory / manifest["events_file"]).read_bytes()
    if hashlib.sha256(content).hexdigest() != manifest["events_sha256"]:
        raise ValueError("events file hash does not match the manifest")
    rows = [json.loads(line) for line in content.decode().splitlines()]
    if len(rows) != manifest["deliveries"]:
        raise ValueError("delivery count does not match the manifest")
    if event_id_digest(row["event_id"] for row in rows) != manifest["event_ids_sha256"]:
        raise ValueError("event-ID hash does not match the manifest")
    return rows, manifest


def _utc(value: str) -> datetime:
    parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    if parsed.tzinfo is None:
        raise argparse.ArgumentTypeError("start must include a UTC offset, e.g. 2026-02-01T00:00Z")
    return parsed


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Export a versioned synthetic fixture")
    parser.add_argument("--version", required=True, help="Fixture label, e.g. parity-v1")
    parser.add_argument("--seed", type=int, required=True,
                        help="Use a seed never published to the topic; it forms the ID prefix")
    parser.add_argument("--count", type=int, default=1000, help="Unique events")
    parser.add_argument("--start", type=_utc, required=True,
                        help="UTC start; choose a date after every event already in silver")
    parser.add_argument("--out", type=Path,
                        help="Directory (default data/fixtures/<version>)")
    args = parser.parse_args(argv)
    directory = args.out or Path("data/fixtures") / args.version
    manifest = write_fixture(directory, args.version, count=args.count, seed=args.seed,
                             start=args.start)
    print(json.dumps({"directory": str(directory), "fixture_version": args.version,
                      "deliveries": manifest["deliveries"],
                      "unique_event_ids": manifest["unique_event_ids"],
                      "event_ids_sha256": manifest["event_ids_sha256"]}))


if __name__ == "__main__":
    main()
